// Generates the seed migration from data/videos.json + the plan in src/lib/plan.ts.
// Run: npm run seed:gen
import { readFileSync, writeFileSync } from "node:fs";
import { assignVideos, PLAN_DAYS, type Level } from "../src/lib/plan.ts";

type RawVideo = {
  youtube_id: string;
  title: string;
  channel: string;
  level: Level;
  ds_level: number | null;
  duration_min: number;
  topic: string;
};

const OUT = "supabase/migrations/20261102120100_cinput_seed.sql";
const videos: RawVideo[] = JSON.parse(readFileSync("data/videos.json", "utf8"));

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lit = (v: string | number | boolean | null) =>
  v === null ? "null" : typeof v === "string" ? q(v) : String(v);

const assignment = assignVideos(videos.map((v) => ({ key: v.youtube_id, level: v.level, duration_min: v.duration_min })));

const lines: string[] = ["-- Generated by scripts/gen-seed.ts. Do not edit by hand.", ""];

lines.push("insert into cinput.plan_days (day_number, week, focus, level_label, target, is_review) values");
lines.push(
  PLAN_DAYS.map(
    (d) => `  (${[d.day_number, d.week, d.focus, d.level_label, d.target, d.is_review].map(lit).join(", ")})`,
  ).join(",\n") + "\non conflict (day_number) do nothing;",
  "",
);

lines.push("insert into cinput.videos (youtube_id, url, title, channel, level, ds_level, duration_min, topic) values");
lines.push(
  videos
    .map(
      (v) =>
        `  (${[
          v.youtube_id,
          `https://www.youtube.com/watch?v=${v.youtube_id}`,
          v.title,
          v.channel,
          v.level,
          v.ds_level,
          v.duration_min,
          v.topic,
        ]
          .map(lit)
          .join(", ")})`,
    )
    .join(",\n") + "\non conflict (youtube_id) do nothing;",
  "",
);

const pairs = [...assignment].flatMap(([day, keys]) => keys.map((k, i) => `  (${day}, ${q(k)}, ${i})`));
lines.push(
  "insert into cinput.day_videos (day_number, video_id, position)",
  "select s.day_number, v.id, s.position from (values",
  pairs.join(",\n"),
  ") as s (day_number, youtube_id, position)",
  "join cinput.videos v on v.youtube_id = s.youtube_id",
  "on conflict do nothing;",
  "",
);

writeFileSync(OUT, lines.join("\n"));

for (const [day, keys] of [...assignment].sort(([a], [b]) => a - b)) {
  const vids = keys.map((k) => videos.find((v) => v.youtube_id === k)!);
  console.log(
    `day ${String(day).padStart(2)}: ${vids.reduce((s, v) => s + v.duration_min, 0)} min  ${vids.map((v) => `${v.level}/${v.duration_min}`).join(", ")}`,
  );
}
console.log(`wrote ${OUT}`);
